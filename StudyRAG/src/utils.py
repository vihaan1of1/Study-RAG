"""StudyRAG Utility Functions.

Provides hashing, text sanitization, citation formatting, and export helpers.
"""

from __future__ import annotations

import hashlib
import re
from datetime import datetime
from typing import Any, Dict


def compute_file_hash(file_bytes: bytes) -> str:
    """Compute a SHA-256 hash of the binary file content."""
    sha = hashlib.sha256()
    sha.update(file_bytes)
    return sha.hexdigest()[:16]


def sanitize_text(text: str) -> str:
    """Clean and normalize extracted text."""
    if not text:
        return ""
    # Strip null bytes and non-printable control characters except \n, \t, \r
    text = re.sub(r"[\x00-\x08\x0b\x0c\x0e-\x1f\x7f]", "", text)
    # Normalize multiple carriage returns and strange line breaks
    text = text.replace("\r\n", "\n").replace("\r", "\n")
    # Replace multiple spaces/tabs on single line
    text = re.sub(r"[ \t]+", " ", text)
    # Replace 3 or more consecutive newlines with 2
    text = re.sub(r"\n{3,}", "\n\n", text)
    return text.strip()


def format_citation(filename: str, page_number: int) -> str:
    """Produce standardized citation string."""
    return f"{filename} (Page {page_number})"


def truncate_preview(text: str, max_len: int = 300) -> str:
    """Truncate long text cleanly at sentence or word boundary for preview."""
    if len(text) <= max_len:
        return text
    snippet = text[:max_len].rsplit(" ", 1)[0]
    return f"{snippet}..."


def build_markdown_export(title: str, content: str, metadata: Dict[str, Any] | None = None) -> str:
    """Package study notes or revision materials into downloadable Markdown."""
    timestamp = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    header = [
        f"# {title}",
        f"**Generated by StudyRAG** on *{timestamp}*",
    ]
    if metadata:
        header.append("")
        header.append("### Document Context")
        for k, v in metadata.items():
            header.append(f"- **{k}**: {v}")
    header.append("\n---\n")
    return "\n".join(header) + "\n" + content
